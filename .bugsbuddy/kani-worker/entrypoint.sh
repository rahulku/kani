#!/bin/sh
set -eu

if [ ! -f /source/Cargo.toml ]; then
  echo "No Cargo.toml was found in the staged source tree." >&2
  exit 2
fi

cp -R -L /source/. /workspace/

# External crates must be supplied by the source archive as a reviewed vendor/
# tree. A cargo vendor-generated .cargo/config.toml is preferred; create the
# equivalent configuration for archives that include vendor/ but omit it.
if [ -d /workspace/vendor ] && [ ! -f /workspace/.cargo/config ] && [ ! -f /workspace/.cargo/config.toml ]; then
  mkdir -p /workspace/.cargo
  cat > /workspace/.cargo/config.toml <<'EOF'
[source.crates-io]
replace-with = "sabkaproof-vendored-sources"

[source.sabkaproof-vendored-sources]
directory = "vendor"
EOF
fi

# Keep the dependency tree immutable during the run. Cargo only needs read
# access to vendored sources and their checksums.
if [ -d /workspace/vendor ]; then
  chmod -R a-w /workspace/vendor
fi

metadata_output=$(mktemp /tmp/sabkaproof-cargo-metadata.XXXXXX)
trap 'rm -f "$metadata_output"' EXIT
if ! cargo metadata --offline --format-version 1 >"$metadata_output" 2>&1; then
  cat "$metadata_output" >&2
  echo >&2
  echo "SabkaProof offline dependency check failed: a required Rust dependency is unavailable in the isolated worker." >&2
  echo "Include a reviewed vendor/ directory generated by cargo vendor and its .cargo/config.toml; network access is disabled during verification." >&2
  exit 3
fi

# Native Kani processing remains authoritative (raw CBMC reachability failures
# are not application defects). A separate pass adds evidence, never verdicts.
primary_status=0
run_kani() {
  if [ -n "${BUGSBUDDY_KANI_HARNESS:-}" ]; then
    cargo --offline kani --harness "$BUGSBUDDY_KANI_HARNESS" "$@"
  else
    cargo --offline kani autoharness -Z autoharness "$@"
  fi
}
run_kani --output-format regular || primary_status=$?
if [ "$primary_status" -eq 1 ]; then
  printf '\nBUGSBUDDY_KANI_EVIDENCE_BEGIN\n'
  run_kani \
  -Z unstable-options \
  --output-format old \
  --no-slice-formula \
  --cbmc-args --xml-ui --trace || echo "Supplementary Kani evidence pass did not complete." >&2
fi
exit "$primary_status"
